    /** @var array<string, string>|null */
    private static ?array $codesByName = null;

    public static function fromCountry(?int $id, ?string $name): ?string
    {
        if ($id !== null && isset(self::COUNTRIES[$id])) {
            return self::COUNTRIES[$id][0];
        }

        if ($name === null || $name === '') {
            return null;
        }

        if (self::$codesByName === null) {
            self::$codesByName = array_column(self::COUNTRIES, 0, 1);
        }

        return self::$codesByName[$name] ?? null;
    }
